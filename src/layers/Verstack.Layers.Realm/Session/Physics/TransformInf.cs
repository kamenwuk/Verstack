using Verstack.Shared.Maths;

namespace Verstack.Layers.Realm;

/// <summary>
/// Постоянное ECS-состояние присутствия сущности в игровом мире — её положение в
/// пространстве (и в будущем поворот/масштаб). Живёт всю сессию сущности (суффикс
/// <c>...Inf</c> по конвенции времени жизни компонентов проекта).
///
/// <para><b>Универсально для любого обитателя мира</b>: игрок, моб, item entity, vehicle —
/// все «выбращены» в мир через <see cref="TransformInf"/>. Это единый источник истины о
/// том, где сущность находится: chunk-observer читает его для центра загрузки чанков,
/// будущая гравитация — для интегрирования движения, AI мобов — для перемещения.</para>
///
/// <para>Источники обновления различны: ввод игрока (через <see cref="Movement.MoveReq"/> +
/// <c>CommitTransformSystem</c>), серверный ТП, knockback, AI. Сам компонент не знает,
/// кто его обновил — он просто текущее состояние.</para>
///
/// <para>Сеётся в <c>HandoffApprovalSystem</c> при входе сущности в мир (для игрока — из
/// спавн-поинта). Позиция — в мировых координатах (block units).</para>
/// </summary>
public struct TransformInf
{
    /// <summary>Мировое положение сущности (block units, float).</summary>
    public Vector3 Position;
}